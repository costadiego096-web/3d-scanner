package com.example.engine

import android.content.ClipData
import android.content.ClipboardManager
import android.content.Context
import android.content.Intent
import android.net.Uri
import androidx.core.content.FileProvider
import com.example.model.Model3D
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object ObjExporter {

    /**
     * Generates a standard Wavefront OBJ formatted string.
     * Includes vertices with optional vertex color, normals, and triangulated face indices.
     * OBJ indexing is 1-based.
     */
    fun generateObjString(model: Model3D): String {
        val sb = StringBuilder()
        val dateStr = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.getDefault()).format(Date(model.timestamp))

        sb.append("# Wavefront OBJ File\n")
        sb.append("# Generated by Scan3D Studio\n")
        sb.append("# Model: ${model.name}\n")
        sb.append("# Created: $dateStr\n")
        sb.append("# Vertices: ${model.vertices.size}\n")
        sb.append("# Faces: ${model.faces.size}\n")
        sb.append("# Bounding Box (cm approx): ")
        sb.append(String.format(Locale.US, "%.1f x %.1f x %.1f\n\n",
            model.boundingBox.width * 10f,
            model.boundingBox.height * 10f,
            model.boundingBox.depth * 10f
        ))

        sb.append("o ${model.name.replace("\\s+".toRegex(), "_")}\n\n")

        // 1. Vertices (v x y z r g b)
        sb.append("# Vertices (position + color)\n")
        for (v in model.vertices) {
            val r = android.graphics.Color.red(v.color) / 255.0f
            val g = android.graphics.Color.green(v.color) / 255.0f
            val b = android.graphics.Color.blue(v.color) / 255.0f
            sb.append(String.format(Locale.US, "v %.4f %.4f %.4f %.3f %.3f %.3f\n", v.x, v.y, v.z, r, g, b))
        }
        sb.append("\n")

        // 2. Vertex Normals (vn nx ny nz)
        sb.append("# Vertex Normals\n")
        // Build per-vertex or per-face normals
        for (f in model.faces) {
            val n = f.normal
            sb.append(String.format(Locale.US, "vn %.4f %.4f %.4f\n", n.x, n.y, n.z))
        }
        sb.append("\n")

        // 3. Faces (f v1//vn1 v2//vn2 v3//vn3)
        sb.append("# Triangular Faces (1-based index)\n")
        for ((idx, f) in model.faces.withIndex()) {
            val normalIdx = idx + 1
            // 1-based indexing for vertices: v1 + 1, v2 + 1, v3 + 1
            sb.append("f ${f.v1 + 1}//$normalIdx ${f.v2 + 1}//$normalIdx ${f.v3 + 1}//$normalIdx\n")
        }

        return sb.toString()
    }

    /**
     * Writes the OBJ string into the app cache directory and returns the File.
     */
    fun saveObjToCache(context: Context, model: Model3D): File {
        val safeName = model.name.replace("[^a-zA-Z0-9_-]".toRegex(), "_").ifEmpty { "model" }
        val fileName = "${safeName}_${model.id.take(6)}.obj"
        val cacheDir = File(context.cacheDir, "exports")
        if (!cacheDir.exists()) {
            cacheDir.mkdirs()
        }
        val file = File(cacheDir, fileName)
        val objString = generateObjString(model)

        FileOutputStream(file).use { out ->
            out.write(objString.toByteArray(Charsets.UTF_8))
        }
        return file
    }

    /**
     * Creates an Android Share Intent with FileProvider URI to share the .obj file.
     */
    fun createShareIntent(context: Context, model: Model3D): Intent {
        val file = saveObjToCache(context, model)
        val authority = "${context.packageName}.fileprovider"
        val contentUri: Uri = FileProvider.getUriForFile(context, authority, file)

        return Intent(Intent.ACTION_SEND).apply {
            type = "model/obj"
            putExtra(Intent.EXTRA_STREAM, contentUri)
            putExtra(Intent.EXTRA_SUBJECT, "Modello 3D OBJ: ${model.name}")
            putExtra(Intent.EXTRA_TEXT, "File 3D Wavefront OBJ esportato con Scan3D Studio: ${model.name} (${model.vertices.size} vertici, ${model.faces.size} facce)")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
    }

    /**
     * Copies the OBJ ASCII representation to the system clipboard.
     */
    fun copyToClipboard(context: Context, model: Model3D) {
        val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
        val clip = ClipData.newPlainText("3D OBJ Model - ${model.name}", generateObjString(model))
        clipboard.setPrimaryClip(clip)
    }
}
